/**
 * scripts/build_card_bundle.mjs
 * 
 * Compiles engine/cards/registry.js, engine/cards/condition_dsl.js, and all
 * PerCardRegistry set modules into a standalone browser-executable
 * engine/cards/bundle.js for arena.html.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function stripModuleSyntax(src) {
  return src
    .replace(/import\s*\{[\s\S]*?\}\s*from\s*['"][^'"]*['"];?/g, '')
    .replace(/export\s+class\s+/g, 'class ')
    .replace(/export\s+const\s+/g, 'const ')
    .replace(/export\s+function\s+/g, 'function ')
    .replace(/export\s+default\s+[^;]+;/g, '');
}

const registrySrc = stripModuleSyntax(fs.readFileSync(path.join(rootDir, 'engine/cards/registry.js'), 'utf8'));
const dslSrc = stripModuleSyntax(fs.readFileSync(path.join(rootDir, 'engine/cards/condition_dsl.js'), 'utf8'));

const setFiles = [
  'sd65_four_demon_lords.js',
  'standard_and_custom_decks.js',
  'soul_drive_cards.js',
  'bs01_cards.js',
  'bs02_cards.js',
  'bs03_cards.js',
  'bs04_cards.js',
  'bs05_cards.js',
  'bs06_cards.js',
  'bs07_cards.js',
  'bs08_cards.js',
  'bs09_cards.js',
  'sd01_sd02_promos_cards.js',
  'bs10_cards.js',
  'bs11_cards.js',
  'bs12_cards.js',
  'bs13_cards.js',
  'sd03_bsc05_constellation_promos_cards.js',
  'bs14_cards.js',
  'bs15_cards.js',
  'bs16_cards.js',
  'bs17_cards.js',
  'bs18_cards.js',
  'sd06_sd11_heroes_promos_cards.js',
  'bs19_cards.js',
  'bs20_cards.js',
  'bs21_cards.js',
  'bs22_cards.js',
  'bs23_cards.js',
  'sd12_sd17_swordblade_promos_cards.js'
];

const setChunks = setFiles.map(file => {
  const fullPath = path.join(rootDir, 'engine/cards/sets', file);
  if (!fs.existsSync(fullPath)) return '';
  return `  // --- SET: ${file.toUpperCase()} ---\n` + stripModuleSyntax(fs.readFileSync(fullPath, 'utf8'));
}).join('\n\n');

const bundleContent = `/**
 * engine/cards/bundle.js
 * 
 * Standalone Browser Bundle of Battle Spirits Eternal Deterministic Per-Card Registry.
 * Includes Two-Tier Booster Set Saga Handlers (BS01-BS09, SD01-SD02, Promos),
 * SD65 Four Demon Lords, Standard/Custom Decks, and Soul Drive Suite.
 * Automatically generated by scripts/build_card_bundle.mjs.
 */

(function(global) {
  'use strict';

  // --- REGISTRY DEFINITION ---
  ${registrySrc}

  // --- TWO-TIER CONDITION & SUB-EFFECT DSL ---
  ${dslSrc}

  // Ensure global assignment
  global.CardRegistry = CardRegistry;
  global.PerCardRegistry = PerCardRegistry;
  global.SagaConditionDSL = SagaConditionDSL;

${setChunks}

  console.log('[PerCardRegistry Bundle] Successfully loaded ' + PerCardRegistry.getAll().length + ' explicit card definitions into arena.');
})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
`;

fs.writeFileSync(path.join(rootDir, 'engine/cards/bundle.js'), bundleContent, 'utf8');
console.log('[build_card_bundle] Successfully generated engine/cards/bundle.js');
