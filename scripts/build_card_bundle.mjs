/**
 * scripts/build_card_bundle.mjs
 * 
 * Compiles engine/cards/registry.js and its set modules into a standalone
 * browser-executable engine/cards/bundle.js for arena.html.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const registrySrc = fs.readFileSync(path.join(rootDir, 'engine/cards/registry.js'), 'utf8');
const sd65Src = fs.readFileSync(path.join(rootDir, 'engine/cards/sets/sd65_four_demon_lords.js'), 'utf8');
const stdSrc = fs.readFileSync(path.join(rootDir, 'engine/cards/sets/standard_and_custom_decks.js'), 'utf8');

// Strip import/export statements for standalone browser evaluation
const cleanRegistry = registrySrc
  .replace(/export class/g, 'class')
  .replace(/export const PerCardRegistry/g, 'const PerCardRegistry')
  .replace(/export default [^;]+;/g, '');

const cleanSd65 = sd65Src
  .replace(/import\s*\{[^}]*\}\s*from\s*['"][^'"]*['"];?/g, '');

const cleanStd = stdSrc
  .replace(/import\s*\{[^}]*\}\s*from\s*['"][^'"]*['"];?/g, '');

const bundleContent = `/**
 * engine/cards/bundle.js
 * 
 * Standalone Browser Bundle of Battle Spirits Eternal Deterministic Per-Card Registry.
 * Automatically generated by scripts/build_card_bundle.mjs.
 */

(function(global) {
  'use strict';

  // --- REGISTRY DEFINITION ---
  ${cleanRegistry}

  // Ensure global assignment
  global.CardRegistry = CardRegistry;
  global.PerCardRegistry = PerCardRegistry;

  // --- SET: SD65 FOUR DEMON LORDS ---
  ${cleanSd65}

  // --- SET: STANDARD AND CUSTOM DECKS ---
  ${cleanStd}

  console.log('[PerCardRegistry Bundle] Successfully loaded ' + PerCardRegistry.getAll().length + ' explicit card definitions into arena.');
})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
`;

fs.writeFileSync(path.join(rootDir, 'engine/cards/bundle.js'), bundleContent, 'utf8');
console.log('[build_card_bundle] Successfully generated engine/cards/bundle.js');
