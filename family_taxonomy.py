def get_family_category_map():
    """Returns a lookup dict: family_name_lower -> (category_key, subcategory_title)."""
    mapping = {}
    for cat_key, cat_data in FAMILY_TAXONOMY.items():
        if "families" in cat_data:
            for f in cat_data["families"]:
                mapping[f.lower()] = (cat_key, None)
        elif "subsections" in cat_data:
            for sub in cat_data["subsections"]:
                for f in sub["families"]:
                    mapping[f.lower()] = (cat_key, sub["title"])
    return mapping
